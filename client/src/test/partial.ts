/**
 * 测试专用的「部分对象」构造器（前端侧）
 * ============================================================================
 * 与 server/src/test/partial.ts 同名同义：把「构造不完整的测试替身」所需的
 * 类型擦除**集中到一个文件**，其余调用点保持强类型提示与 IDE 补全。
 *
 * 存在的理由与 server 侧完全一致——`as never` 会让字段名拼错、必填项缺失
 * 全部编译通过，于是用例只验自己造的那几个字段，真实结构改了测试照样绿。
 *
 * 用法：
 *   const req = partial<HistoryItem>({ id: 'h1' });
 *   //                       ^^^^^ 显式目标类型；多写/写错字段名仍会被拦
 *
 * 只用于测试。生产代码出现 `as unknown as` 由 server 侧的 typeEscape 守卫守门。
 */

/**
 * 构造一个只实现了 `T` 部分成员的测试替身。
 *
 * 相比 `as never`：对象字面量里多写或写错字段名仍会被 TypeScript 拦下，
 * 只有「缺字段」被有意放过 —— 而缺字段正是测试桩的正常形态。
 */
export function partial<T>(value: Partial<T>): T {
  return value as T;
}
